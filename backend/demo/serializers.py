    second_flr_area = serializers.FloatField(read_only=True, allow_null=True)
    total_area = serializers.FloatField(read_only=True, allow_null=True)
    area_sqm = serializers.FloatField(read_only=True, allow_null=True)
    mhada_transfer_order = serializers.CharField(read_only=True, allow_null=True)
    transfer_status = serializers.CharField(read_only=True, allow_null=True)
    possession_date = serializers.CharField(read_only=True, allow_null=True)
    mhada_transfer = serializers.CharField(read_only=True, allow_null=True)
    status = serializers.CharField(read_only=True, allow_null=True)
    centroid_json = serializers.CharField(read_only=True, allow_null=True)
    polygon_json = serializers.CharField(read_only=True, allow_null=True)
