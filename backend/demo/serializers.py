    layout = serializers.CharField(read_only=True, allow_null=True)
    plot_number = serializers.CharField(read_only=True, allow_null=True)
    occupant = serializers.CharField(read_only=True, allow_null=True)
    first_allottee = serializers.CharField(read_only=True, allow_null=True)
    owner_name = serializers.CharField(read_only=True, allow_null=True)
    type_of_code = serializers.CharField(read_only=True, allow_null=True)
